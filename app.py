@app.post("/api/sources")
def create_source():
    d = request.get_json(force=True)
    try:
        with engine.begin() as conn:
            conn.execute(text("""
                INSERT INTO sources(name,url,source_type,enabled)
                VALUES(:name,:url,:source_type,1)
            """), {
                "name": d["name"].strip(), "url": d["url"].strip(),
                "source_type": d.get("source_type","rss")
            })
        return jsonify({"ok":True}), 201
    except IntegrityError:
        return jsonify({"ok":False,"error":"Source URL already exists"}), 409

@app.patch("/api/sources/<int:source_id>")
def update_source(source_id):
    d = request.get_json(force=True)
    enabled = 1 if d.get("enabled") else 0
    with engine.begin() as conn:
        conn.execute(text("UPDATE sources SET enabled=:enabled WHERE id=:id"),
                     {"enabled":enabled, "id":source_id})
    return jsonify({"ok":True})

