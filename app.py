@app.get("/api/leads")
def leads():
    with engine.connect() as conn:
        rows = rows_as_dicts(conn.execute(text("SELECT * FROM leads ORDER BY id DESC")))
    return jsonify(rows)

@app.post("/api/leads")
def create_lead():
    ok = add_lead(request.get_json(force=True))
    return jsonify({"ok": ok}), 201 if ok else 409

@app.patch("/api/leads/<int:lead_id>")
def update_lead(lead_id):
    data = request.get_json(force=True)
    allowed = {"status","priority","notes","company","location","category","deadline"}
    chosen = {k:v for k,v in data.items() if k in allowed}
    if not chosen:
        return jsonify({"ok":False}), 400
    assignments = ", ".join(f"{k}=:{k}" for k in chosen)
    chosen["id"] = lead_id
    with engine.begin() as conn:
        conn.execute(text(f"UPDATE leads SET {assignments} WHERE id=:id"), chosen)
    return jsonify({"ok":True})

@app.delete("/api/leads/<int:lead_id>")
def delete_lead(lead_id):
    with engine.begin() as conn:
        conn.execute(text("DELETE FROM leads WHERE id=:id"), {"id": lead_id})
    return jsonify({"ok":True})

