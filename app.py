def rows_as_dicts(result):
    return [dict(r) for r in result.mappings().all()]

def init_db():
    statements = [
        """
        CREATE TABLE IF NOT EXISTS leads (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            uid TEXT UNIQUE NOT NULL,
            title TEXT NOT NULL,
            company TEXT DEFAULT '',
            location TEXT DEFAULT '',
            category TEXT DEFAULT '',
            intent TEXT DEFAULT '',
            priority TEXT DEFAULT 'B',
            status TEXT DEFAULT 'New',
            source_name TEXT DEFAULT '',
            source_url TEXT DEFAULT '',
            lead_url TEXT NOT NULL,
            published_at TEXT DEFAULT '',
            deadline TEXT DEFAULT '',
            notes TEXT DEFAULT '',
            created_at TEXT NOT NULL
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS sources (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name TEXT NOT NULL,
            url TEXT UNIQUE NOT NULL,
            source_type TEXT NOT NULL DEFAULT 'rss',
            enabled INTEGER NOT NULL DEFAULT 1,
            last_sync TEXT DEFAULT '',
            last_result TEXT DEFAULT ''
        )
        """
    ]
    # SQLite does not support the Postgres identity syntax, so use compatible DDL locally.
    if DATABASE_URL.startswith("sqlite:"):
        statements = [
            statements[0].replace("INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", "INTEGER PRIMARY KEY AUTOINCREMENT"),
            statements[1].replace("INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", "INTEGER PRIMARY KEY AUTOINCREMENT")
        ]
    with engine.begin() as conn:
        for stmt in statements:
            conn.execute(text(stmt))
    seed()

