def uid_for(title, url):
    raw = (title.strip().lower() + "|" + url.strip().lower()).encode()
    return hashlib.sha256(raw).hexdigest()[:24]

def add_lead(x):
    title_v = (x.get("title") or "Untitled lead").strip()
    lead_url = (x.get("lead_url") or x.get("source_url") or "").strip()
    if not lead_url:
        return False
    fields = {
        "uid": uid_for(title_v, lead_url), "title": title_v,
        "company": x.get("company",""), "location": x.get("location",""),
        "category": x.get("category",""), "intent": x.get("intent",""),
        "priority": x.get("priority","B"), "status": x.get("status","New"),
        "source_name": x.get("source_name",""), "source_url": x.get("source_url",""),
        "lead_url": lead_url, "published_at": x.get("published_at",""),
        "deadline": x.get("deadline",""), "notes": x.get("notes",""),
        "created_at": datetime.now(timezone.utc).isoformat(timespec="seconds")
    }
    try:
        with engine.begin() as conn:
            conn.execute(text("""
                INSERT INTO leads(uid,title,company,location,category,intent,priority,status,
                source_name,source_url,lead_url,published_at,deadline,notes,created_at)
                VALUES(:uid,:title,:company,:location,:category,:intent,:priority,:status,
                :source_name,:source_url,:lead_url,:published_at,:deadline,:notes,:created_at)
            """), fields)
        return True
    except IntegrityError:
        return False

def score_text(value):
    t = re.sub(r"\s+", " ", (value or "").lower())
    ev = sum(1 for k in EV_TERMS if k in t)
    intent = sum(1 for k in INTENT_TERMS if k in t)
    loc = sum(1 for k in PRIORITY_LOCATIONS if k in t)
    score = ev*4 + intent*2 + loc*3
    if ev == 0 or intent == 0:
        return 0, "C"
    priority = "A+++" if score >= 15 else "A++" if score >= 11 else "A+" if score >= 8 else "A" if score >= 6 else "B"
    return score, priority

def location_hint(value):
    lower = (value or "").lower()
    hits = [x for x in PRIORITY_LOCATIONS if x in lower]
    return ", ".join(dict.fromkeys(h.title() for h in hits[:3]))

def sync_rss(source):
    feed = feedparser.parse(source["url"], request_headers={"User-Agent": USER_AGENT})
    new_count = 0
    for entry in feed.entries[:100]:
        title_v = getattr(entry, "title", "") or ""
        summary = getattr(entry, "summary", "") or ""
        link = getattr(entry, "link", "") or source["url"]
        combined = BeautifulSoup(title_v + " " + summary, "html.parser").get_text(" ", strip=True)
        score, priority = score_text(combined)
        if score == 0:
            continue
        if add_lead({
            "title": title_v[:500], "location": location_hint(combined),
            "category": "Auto-discovered", "intent": combined[:900],
            "priority": priority, "source_name": source["name"],
            "source_url": source["url"], "lead_url": link,
            "published_at": getattr(entry, "published", "") or getattr(entry, "updated", ""),
            "notes": f"Auto-added from RSS. Match score: {score}. Verify requirement before outreach."
        }):
            new_count += 1
    return new_count

def sync_html(source):
    r = requests.get(source["url"], timeout=20, headers={"User-Agent": USER_AGENT})
    r.raise_for_status()
    soup = BeautifulSoup(r.text, "html.parser")
    new_count, seen = 0, set()
    for a in soup.find_all("a", href=True):
        href = urljoin(source["url"], a["href"])
        title_v = a.get_text(" ", strip=True)
        parent = a.parent.get_text(" ", strip=True) if a.parent else title_v
        combined = (title_v + " " + parent)[:3000]
        if not title_v or href in seen:
            continue
        seen.add(href)
        score, priority = score_text(combined)
        if score == 0:
            continue
        if add_lead({
            "title": title_v[:500], "location": location_hint(combined),
            "category": "Auto-discovered", "intent": parent[:900],
            "priority": priority, "source_name": source["name"],
            "source_url": source["url"], "lead_url": href,
            "notes": f"Auto-added from public webpage. Match score: {score}. Verify source terms and requirement."
        }):
            new_count += 1
    return new_count

def sync_all():
    with engine.connect() as conn:
        sources = rows_as_dicts(conn.execute(text("SELECT * FROM sources WHERE enabled=1")))
    total = 0
    for source in sources:
        result = ""
        try:
            if source["source_type"] == "rss":
                n = sync_rss(source)
            elif source["source_type"] == "html":
                n = sync_html(source)
            else:
                n = 0
                result = "Unsupported source type"
            total += n
            result = result or f"OK — {n} new lead(s)"
        except Exception as exc:
            result = f"Error: {str(exc)[:180]}"
        with engine.begin() as conn:
            conn.execute(text("""
                UPDATE sources SET last_sync=:last_sync, last_result=:last_result WHERE id=:id
            """), {
                "last_sync": datetime.now(timezone.utc).isoformat(timespec="seconds"),
                "last_result": result, "id": source["id"]
            })
    return total

